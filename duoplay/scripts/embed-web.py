"""Turns the web app into a C++ source file so the bridge is a single self-contained binary.

    python3 scripts/embed-web.py <web-dir> <output.cpp>
"""
import mimetypes
import os
import sys

TYPES = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "text/javascript; charset=utf-8",
         ".webmanifest": "application/manifest+json", ".png": "image/png", ".mp4": "video/mp4", ".svg": "image/svg+xml",
         ".json": "application/json", ".cer": "application/x-x509-ca-cert"}


def main(web, out):
    files = []
    for root, _, names in os.walk(web):
        for n in sorted(names):
            if n.startswith("."):
                continue
            full = os.path.join(root, n)
            rel = os.path.relpath(full, web).replace(os.sep, "/")
            files.append((rel, full))
    files.sort()
    lines = ['// Generated by scripts/embed-web.py. Do not edit.', '#include "embedded_web.hpp"', "", "namespace duo {", ""]
    for i, (rel, full) in enumerate(files):
        data = open(full, "rb").read()
        lines.append(f"static const unsigned char f{i}[{max(1, len(data))}] = {{")
        for off in range(0, len(data), 24):
            lines.append("\t" + ",".join(f"0x{b:02x}" for b in data[off:off + 24]) + ",")
        lines.append("};")
    lines.append("")
    lines.append("const EmbeddedFile kEmbeddedWeb[] = {")
    for i, (rel, full) in enumerate(files):
        ext = os.path.splitext(rel)[1].lower()
        mime = TYPES.get(ext) or mimetypes.guess_type(rel)[0] or "application/octet-stream"
        size = os.path.getsize(full)
        lines.append(f'\t{{"{rel}", "{mime}", f{i}, {size}}},')
    lines.append("};")
    lines.append(f"const size_t kEmbeddedWebCount = {len(files)};")
    lines.append("")
    lines.append("} // namespace duo")
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.replace(tmp, out)
    print(f"embedded {len(files)} web files ({sum(os.path.getsize(p) for _, p in files) // 1024} KB)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
